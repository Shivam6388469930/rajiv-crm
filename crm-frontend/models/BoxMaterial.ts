// models/BoxMaterial.ts
import { Schema, model, models } from "mongoose";

const boxMaterialSchema = new Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
    },
    slug: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true,
    },
    status: {
      type: String,
      enum: ["active", "inactive"],
      default: "active",
    },
  },
  {
    timestamps: true,
  }
);

export default models.BoxMaterial || model("BoxMaterial", boxMaterialSchema);